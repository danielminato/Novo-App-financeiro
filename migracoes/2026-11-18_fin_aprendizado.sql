create table if not exists public.fin_licoes (
  id         bigint generated by default as identity primary key,
  texto      text not null,
  ativo      boolean not null default true,
  criado_em  timestamptz not null default now()
);

-- Conversas guardadas (o histórico vai inteiro, tal como a API o devolve)
create table if not exists public.fin_conversas (
  id            bigint generated by default as identity primary key,
  titulo        text,
  mensagens     jsonb not null default '[]'::jsonb,
  propostas     jsonb not null default '[]'::jsonb,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
drop trigger if exists fin_tocar on public.fin_conversas;
create trigger fin_tocar before update on public.fin_conversas for each row execute function public.fin_tocar();

do $$
declare t text;
begin
  foreach t in array array['fin_licoes', 'fin_conversas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "master usa" on public.%I', t);
    execute format('create policy "master usa" on public.%I for all using (public.nivel_atual() = ''master'') with check (public.nivel_atual() = ''master'')', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- para a função de IA saber quem chama (só o master pode usar)
grant execute on function public.nivel_atual() to authenticated;

select tablename, rowsecurity from pg_tables where tablename in ('fin_licoes', 'fin_conversas');
