create or replace function public.eh_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.admins a where lower(a.email) = lower(auth.jwt() ->> 'email'))
$$;
grant execute on function public.eh_admin() to authenticated;

-- ---------- Listas (estrutura) ----------
create table if not exists public.fin_categorias (
  id     integer generated by default as identity primary key,
  nome   text not null,
  ativo  boolean not null default true
);
create table if not exists public.fin_subcategorias (
  id              integer generated by default as identity primary key,
  categoria_id    integer not null references public.fin_categorias(id),
  nome            text not null,
  iva_percentual  numeric(5,2) not null default 23,
  ativo           boolean not null default true
);
create table if not exists public.fin_centros_custo (
  id     integer generated by default as identity primary key,
  nome   text not null,
  ativo  boolean not null default true
);
create table if not exists public.fin_formas_pagamento (
  id     integer generated by default as identity primary key,
  nome   text not null unique,
  ativo  boolean not null default true
);
create table if not exists public.fin_canais (
  id     integer generated by default as identity primary key,
  nome   text not null,
  tipo   text not null,          -- dinheiro | cartao | delivery | m20 | gorjeta
  ativo  boolean not null default true
);

-- ---------- Lançamentos ----------
-- Vendas: uma linha por dia (conferência de caixa).
--   Total A = dinheiro + cartoes − gorjetas      Total B = sistema + m20
--   Diferença = A − B                             Faturamento = sistema + m20 + uber + bolt + glovo
create table if not exists public.fin_vendas_dia (
  id            bigint generated by default as identity primary key,
  data          date not null unique,
  dinheiro      numeric(12,2) not null default 0,
  cartoes       numeric(12,2) not null default 0,
  gorjetas      numeric(12,2) not null default 0,
  sistema       numeric(12,2) not null default 0,
  m20           numeric(12,2) not null default 0,
  uber          numeric(12,2) not null default 0,
  bolt          numeric(12,2) not null default 0,
  glovo         numeric(12,2) not null default 0,
  observacoes   text,
  origem_id     integer,                         -- id no sistema antigo (Render)
  criado_por    text default (auth.jwt() ->> 'email'),
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- Compras e despesas. valor = total da fatura (com IVA); valor_iva = IVA contido nesse total.
create table if not exists public.fin_compras (
  id               bigint generated by default as identity primary key,
  data             date not null,
  data_pagamento   date,
  descricao        text,
  fornecedor       text,
  numero_fatura    text,
  categoria_id     integer references public.fin_categorias(id),
  subcategoria_id  integer references public.fin_subcategorias(id),
  centro_custo_id  integer references public.fin_centros_custo(id),
  quem_comprou     text,
  quem_pagou       text,
  forma_pagamento  text,
  valor            numeric(12,2) not null default 0,
  valor_iva        numeric(12,2) not null default 0,
  comprovante      text,                        -- caminho no Storage (mais tarde)
  observacoes      text,
  origem_id        integer,
  criado_por       text default (auth.jwt() ->> 'email'),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now()
);
create index if not exists fin_compras_data_idx on public.fin_compras(data);
create index if not exists fin_compras_pag_idx  on public.fin_compras(data_pagamento);

-- Metas mensais de vendas
create table if not exists public.fin_metas (
  ano          integer not null,
  mes          integer not null check (mes between 1 and 12),
  meta_vendas  numeric(12,2),
  primary key (ano, mes)
);

-- atualizado_em automático
create or replace function public.fin_tocar() returns trigger language plpgsql as $$
begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists fin_tocar on public.fin_vendas_dia;
create trigger fin_tocar before update on public.fin_vendas_dia for each row execute function public.fin_tocar();
drop trigger if exists fin_tocar on public.fin_compras;
create trigger fin_tocar before update on public.fin_compras for each row execute function public.fin_tocar();

-- ---------- Acesso (RLS): só administradores ----------
do $$
declare t text;
begin
  foreach t in array array['fin_categorias','fin_subcategorias','fin_centros_custo','fin_formas_pagamento',
                           'fin_canais','fin_vendas_dia','fin_compras','fin_metas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admins leem" on public.%I', t);
    execute format('create policy "admins leem" on public.%I for select using (public.eh_admin())', t);
    execute format('drop policy if exists "admins criam" on public.%I', t);
    execute format('create policy "admins criam" on public.%I for insert with check (public.eh_admin())', t);
    execute format('drop policy if exists "admins editam" on public.%I', t);
    execute format('create policy "admins editam" on public.%I for update using (public.eh_admin())', t);
    execute format('drop policy if exists "admins apagam" on public.%I', t);
    execute format('create policy "admins apagam" on public.%I for delete using (public.eh_admin())', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- ---------- Ligar a guarda de perfis às tabelas novas ----------
-- (mesmo bloco 6 da migração de perfis, com as listas do financeiro como "estrutura")
do $$
declare
  t record; tipo text; livres text;
  estrutura text[] := array['admins', 'colaboradores', 'areas', 'fornecedores', 'grupos', 'produtos',
                            'receitas', 'receita_itens', 'checklist_itens', 'producao_itens',
                            'custos_fixos', 'impasto_config',
                            'fin_categorias', 'fin_subcategorias', 'fin_centros_custo',
                            'fin_formas_pagamento', 'fin_canais', 'fin_metas'];
begin
  for t in select tablename from pg_tables
           where schemaname = 'public'
             and tablename not in ('alertas_seguranca', 'historico_alteracoes', 'config_privada')
             and tablename not like 'escala\_%' loop
    tipo   := case when t.tablename = any(estrutura) then 'estrutura' else 'lancamento' end;
    livres := case when t.tablename = 'produtos' then 'qtd_atual' else '' end;
    execute format('drop trigger if exists guarda_perfis on public.%I', t.tablename);
    execute format('create trigger guarda_perfis before insert or update or delete on public.%I '
                   'for each row execute function public.guarda_perfis(%L, %L)', t.tablename, tipo, livres);
  end loop;
end $$;

select tablename from pg_tables where schemaname = 'public' and tablename like 'fin\_%' order by 1;
